-- 府库：单机器人数据库 "CuO"，群 schema "<group_id>"。
-- Execute with psql -X -v ON_ERROR_STOP=1 --dbname=CuO --file=001_fuku.sql.
-- This bootstrap is transactional and safe to rerun against its own schema.
-- Existing tables/data are never dropped or rewritten. Future schema changes
-- require a new migration; IF NOT EXISTS does not reconcile unrelated tables.
BEGIN;

DO $migration$
BEGIN
    IF current_database() <> 'CuO' THEN
        RAISE EXCEPTION 'Run this migration in database "CuO", not %', current_database();
    END IF;
END
$migration$;

CREATE SCHEMA IF NOT EXISTS "<group_id>";

CREATE TABLE IF NOT EXISTS "<group_id>".log (
    task_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    triggered_at TIMESTAMPTZ NOT NULL,
    -- Calculated by the caller from the original trigger, using 04:00 Asia/Shanghai.
    business_date DATE NOT NULL,
    request_type TEXT NOT NULL DEFAULT 'message',
    user_id TEXT,
    message_id TEXT,
    original_text TEXT,
    params JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'pending',
    business_status TEXT NOT NULL DEFAULT 'pending',
    step TEXT NOT NULL DEFAULT 'pending',
    result JSONB NOT NULL DEFAULT '{}'::jsonb,
    error JSONB,
    completed_at TIMESTAMPTZ,
    CONSTRAINT log_status_check
        CHECK (status IN ('pending', 'running', 'completed', 'failed', 'needs_review')),
    CONSTRAINT log_business_status_check
        CHECK (business_status IN ('pending', 'running', 'completed', 'failed'))
);

CREATE TABLE IF NOT EXISTS "<group_id>".messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id TEXT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    business_date DATE NOT NULL,
    user_id TEXT NOT NULL,
    nickname TEXT NOT NULL,
    text TEXT NOT NULL DEFAULT '',
    segments JSONB NOT NULL,
    generated_by TEXT,
    processing JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT messages_message_id_key UNIQUE (message_id)
);

CREATE TABLE IF NOT EXISTS "<group_id>".members (
    user_id TEXT PRIMARY KEY,
    nickname TEXT NOT NULL,
    display_name TEXT,
    slots JSONB NOT NULL DEFAULT '[null,null,null,null,null,null]'::jsonb,
    sheet_name TEXT,
    fortune BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT members_six_slots_check CHECK (
        CASE WHEN jsonb_typeof(slots) = 'array' THEN
            jsonb_array_length(slots) = 6
            AND jsonb_typeof(slots -> 0) IN ('string', 'null')
            AND jsonb_typeof(slots -> 1) IN ('string', 'null')
            AND jsonb_typeof(slots -> 2) IN ('string', 'null')
            AND jsonb_typeof(slots -> 3) IN ('string', 'null')
            AND jsonb_typeof(slots -> 4) IN ('string', 'null')
            AND jsonb_typeof(slots -> 5) IN ('string', 'null')
        ELSE FALSE END
    )
);

CREATE TABLE IF NOT EXISTS "<group_id>".summaries (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    task_id UUID NOT NULL,
    business_date DATE NOT NULL,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT summaries_task_id_key UNIQUE (task_id),
    CONSTRAINT summaries_task_id_fkey FOREIGN KEY (task_id)
        REFERENCES "<group_id>".log (task_id) ON DELETE RESTRICT,
    CONSTRAINT summaries_coverage_check CHECK (end_at > start_at)
);

CREATE TABLE IF NOT EXISTS "<group_id>".divinations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    task_id UUID NOT NULL,
    user_id TEXT NOT NULL,
    business_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'generating',
    -- Drafts retain already generated values; missing draft results stay SQL NULL.
    zhou_yi JSONB,
    tarot JSONB,
    dictum JSONB,
    keyword TEXT,
    advice TEXT,
    luck_delta INTEGER,
    fortune_before BIGINT,
    fortune_after BIGINT,
    content TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    settled_at TIMESTAMPTZ,
    CONSTRAINT divinations_task_id_key UNIQUE (task_id),
    CONSTRAINT divinations_user_business_date_key UNIQUE (user_id, business_date),
    CONSTRAINT divinations_task_id_fkey FOREIGN KEY (task_id)
        REFERENCES "<group_id>".log (task_id) ON DELETE RESTRICT,
    CONSTRAINT divinations_user_id_fkey FOREIGN KEY (user_id)
        REFERENCES "<group_id>".members (user_id) ON DELETE RESTRICT,
    CONSTRAINT divinations_status_check
        CHECK (status IN ('generating', 'settled', 'failed')),
    CONSTRAINT divinations_luck_delta_check
        CHECK (luck_delta BETWEEN -10 AND 10),
    CONSTRAINT divinations_settled_complete_check CHECK (
        status <> 'settled' OR (
            zhou_yi IS NOT NULL AND zhou_yi <> 'null'::jsonb
            AND tarot IS NOT NULL AND tarot <> 'null'::jsonb
            AND dictum IS NOT NULL AND dictum <> 'null'::jsonb
            AND keyword IS NOT NULL
            AND advice IS NOT NULL
            AND luck_delta IS NOT NULL
            AND fortune_before IS NOT NULL
            AND fortune_after IS NOT NULL
            AND content IS NOT NULL
            AND settled_at IS NOT NULL
            AND fortune_after::numeric = fortune_before::numeric + luck_delta::numeric
        )
    )
);

-- log.message_id deliberately has no UNIQUE constraint: nickname observation
-- and an @ request can create separate tasks for the same incoming message.
CREATE INDEX IF NOT EXISTS log_message_id_idx
    ON "<group_id>".log (message_id) WHERE message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS log_pending_idx
    ON "<group_id>".log (created_at, task_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS log_recovery_idx
    ON "<group_id>".log (status, created_at)
    WHERE status IN ('running', 'failed', 'needs_review');
CREATE INDEX IF NOT EXISTS log_business_date_idx
    ON "<group_id>".log (business_date, created_at);
CREATE INDEX IF NOT EXISTS log_user_history_idx
    ON "<group_id>".log (user_id, request_type, triggered_at DESC)
    WHERE user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS messages_business_date_idx
    ON "<group_id>".messages (business_date, sent_at, id);
CREATE INDEX IF NOT EXISTS messages_user_sent_at_idx
    ON "<group_id>".messages (user_id, sent_at DESC);
-- Supports containment queries against derived image hashes and processing data.
CREATE INDEX IF NOT EXISTS messages_processing_idx
    ON "<group_id>".messages USING GIN (processing jsonb_path_ops);

CREATE INDEX IF NOT EXISTS summaries_latest_idx
    ON "<group_id>".summaries (business_date, end_at DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS divinations_settled_date_idx
    ON "<group_id>".divinations (business_date, user_id) WHERE status = 'settled';

COMMENT ON SCHEMA "<group_id>" IS 'CuO 府库：群 <group_id>；仅使用已登记群配置选择 schema';
COMMENT ON TABLE "<group_id>".log IS '可恢复任务及永久业务历史，不按普通调试日志定期清空';
COMMENT ON COLUMN "<group_id>".log.business_date IS '调用方按原 triggered_at 与北京时间 04:00 边界显式计算';
COMMENT ON COLUMN "<group_id>".messages.business_date IS '调用方按原 sent_at 与北京时间 04:00 边界显式计算';
COMMENT ON COLUMN "<group_id>".members.slots IS '元谥、亨谥、利谥、贞谥、常谥、平谥；空槽为 JSON null';
COMMENT ON COLUMN "<group_id>".divinations.business_date IS '调用方显式传入原任务业务日期；恢复不可改为执行日期';
COMMENT ON TABLE "<group_id>".divinations IS '同成员同业务日唯一；结算必须与 members.fortune 和 log 同事务更新';

COMMIT;
